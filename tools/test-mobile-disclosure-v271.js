const win={matchMedia:()=>({matches:true})},el=id=>id==='sidebar'?sidebar:null;
vm.runInNewContext(drawerCode,{window:win,document:doc,el});
win.setSafeProjectsMenu(true);
assert.ok(classes.has('menu-open'));
assert.equal(trigger.attrs['aria-expanded'],'true');
assert.equal(first.focusCount,1);assert.equal(bottom.inert,true);
win.setSafeProjectsMenu(false);
assert.ok(!classes.has('menu-open'));
assert.equal(trigger.attrs['aria-expanded'],'false');
