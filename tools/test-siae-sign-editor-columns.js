const assert=require('node:assert/strict');
const fs=require('node:fs');
const vm=require('node:vm');
const read=p=>fs.readFileSync(p,'utf8');
const memory=new Map();
const window={localStorage:{getItem:k=>memory.get(k)||null,setItem:(k,v)=>memory.set(k,v)}};
vm.runInNewContext(read('kyv-siae-amount.js'),{window});
vm.runInNewContext(read('kyv-editor-columns.js'),{window});
const a=window.KYV_SIAE_AMOUNT,c=window.KYV_EDITOR_COLUMNS;
assert.equal(a.raw('-1.234,56'),-1234.56);
assert.equal(a.forUs('-1.234,56'),1234.56);
assert.equal(a.forUs('1.234,56'),-1234.56);
assert.equal(a.forUs('−500,00'),500);
assert.equal(a.forUs('25,00-'),25);
assert.equal(a.forUs('(250,00)'),250);
assert.equal(a.forUs('-2,500.25'),2500.25);
assert.equal(a.forUs(100),-100);
assert.equal(a.forUs(0),0);
assert.equal(a.forUs(''),null);
const full=['ID','TITOLO','ARTISTA','NOTE'];
assert.deepEqual(Array.from(c.visible('PROGETTI',full)),full);
assert.equal(c.set('PROGETTI','ARTISTA',false,full),true);
assert.deepEqual(Array.from(c.visible('PROGETTI',full)),['ID','TITOLO','NOTE']);
assert.deepEqual(Array.from(c.visible('FATTURE',full)),full,'preference must be per table');
assert.equal(c.set('PROGETTI','ID',false,full),true);
assert.equal(c.set('PROGETTI','TITOLO',false,full),true);
assert.equal(c.set('PROGETTI','NOTE',false,full),false,'at least one column must remain');
assert.deepEqual(Array.from(c.visible('PROGETTI',full)),['NOTE']);
assert.equal(c.set('PROGETTI','ARTISTA',true,full),true);
assert.deepEqual(Array.from(c.visible('PROGETTI',full)),['ARTISTA','NOTE']);
c.showAll('PROGETTI');
assert.deepEqual(Array.from(c.visible('PROGETTI',full)),full);
const code=read('editor.html');
assert.ok(code.includes('kyv-editor-columns.js')&&code.includes('data-action="toggle-columns"'));
assert.ok(code.includes('data-action="show-all-columns"'));
assert.ok(code.includes('data-editor-column'));
assert.ok(code.includes('KYV_EDITOR_COLUMNS?.visible(currentEditorTable,Object.keys(sourceRow))'));
assert.ok(code.includes('Object.values(row).some('),'search must include hidden data');
assert.ok(code.includes("const keys = Object.keys(currentEditorData[0]); let csv = keys.join(',')"),'CSV must include hidden data');
assert.ok(code.includes('IMPORTO conserva il segno originale SIAE'));
const rights=read('kyv-rights-v7.js'),intel=read('kyv-intelligence-engine-v238.js'),rend=read('rendiconto.html'),guard=read('kyv-siae-import-guard.js');
assert.ok(rights.includes('amountForUs(row)')&&rights.includes('s+amountForUs(r)'));
assert.ok(intel.includes('KYV_SIAE_AMOUNT?.forUs(v.IMPORTO)'));
assert.ok(rend.includes('KYV_SIAE_AMOUNT?.forUs(r.IMPORTO)'));
assert.ok(guard.includes("'ESTRATTO SIAE':['DATA','OPERAZIONE','IMPORTO']"),'original signatures unchanged');
assert.doesNotMatch(read('kyv-siae-amount.js'),/\.(insert|update|upsert|delete)\(/);
vm.runInNewContext(intel,{window});
const out=window.KYV_INTELLIGENCE_ENGINE.compute({
 siaes:[{DATA:'2026-01-15',IMPORTO:'-1.000,00'},{DATA:'2026-01-17',IMPORTO:'250,00'}],
 rightsLiquidations:[{Ente:'SIAE',DataAccredito:'2026-01-20',ImportoNetto:300}]
},'monthly');
assert.equal(out.rows[0].siaeProvisional,75000,'SIAE provisional: signed from our POV');
assert.equal(out.totals.rightsCash,300,'verified transfer must not be inverted');
assert.equal(out.totals.verifiedCash,0,'SIAE provisional must not be bank cash');
assert.ok(read('sw.js').includes('kyv-studio-v2-63-economy-analyst-20261104'));
console.log('OK: SIAE inverted in calculations only; local per-table column controls preserve data/export.');
