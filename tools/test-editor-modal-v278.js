// v2.78: Studio Editor modal presentation must be entirely separate from DB operations.
const assert=require('node:assert/strict'),fs=require('node:fs'),vm=require('node:vm');
const read=p=>fs.readFileSync(p,'utf8');
const h={};vm.runInNewContext(read('kyv-editor-modal-v278.js'),{window:h});
const api=h.KYV_EDITOR_MODAL_V278;
assert.ok(api&&typeof api.groupFields==='function');
const fields=['TITOLO','ARTISTA','ID_PROGETTO','Data_Sessione','FEE','ROY','NOTE','Numero','DataScadenzaPagamento','PrezzoTotale','Denominazione','Codice_ISRC'];
const groups=api.groupFields(fields);
assert.deepEqual(Array.from(groups,g=>g.id),['principali','collegamenti','date','economia','altri']);
assert.deepEqual(Array.from(groups.flatMap(g=>g.keys)),['TITOLO','ARTISTA','Numero','Denominazione','ID_PROGETTO','Codice_ISRC','Data_Sessione','DataScadenzaPagamento','FEE','ROY','PrezzoTotale','NOTE']);
assert.deepEqual(Array.from(api.groupFields(['TITOLO']),g=>g.id),['principali'],'Empty sections must not be displayed');
assert.equal(api.classify('PAGAMENTO'),'economia');
assert.equal(api.classify('IDFT'),'collegamenti');
assert.equal(api.classify('Data_Pubblicazione'),'date');
assert.equal(api.matchesField('TITOLO','Titolo progetto','titolo'),true);
assert.equal(api.matchesField('Data_Sessione','Data sessione','sEssIoNe'),true);
assert.equal(api.matchesField('ARTISTA','Artista','artist'),true);
assert.equal(api.matchesField('TITOLO','Titolo','nota'),false);
assert.equal(api.matchesField('TITOLO','Titolo','',true,new Set()),false);
assert.equal(api.matchesField('TITOLO','Titolo','',true,new Set(['TITOLO'])),true);
assert.equal(api.matchesField('TITOLO','Titolo','artista',true,new Set(['TITOLO'])),false);
const html=read('editor.html'),helper=read('kyv-editor-modal-v278.js');
assert.equal((html.match(/id="modal-dynamic"/g)||[]).length,1,'Keep exactly one existing editor modal');
assert.equal((html.match(/id="form-dynamic"/g)||[]).length,1,'Do not duplicate save form');
assert.equal((html.match(/id="dynamic-form-fields"/g)||[]).length,1);
for(const key of ['editor-modal-field-search','editor-modal-only-changed','editor-modal-fields-status','editor-modal-empty-fields','editor-modal-change-status','btn-dynamic-salva'])assert.equal((html.match(new RegExp('id="'+key+'"','g'))||[]).length,1,key+' must not be duplicated');
assert.ok(html.includes('kyv-editor-modal-v278.js')&&html.includes('groupFields(keys)'));
assert.ok(html.includes('data-editor-modal-field=')&&html.includes('data-editor-modal-section='));
assert.ok(html.includes('data-editor-modal-label=')&&html.includes('data-key='));
assert.ok(html.includes('label for="\${fieldId}"'),'Labels must target actual input ID');
assert.ok(html.includes('allFieldHtml.set(key,'),'Retain every input by key');
assert.ok(html.includes('formRoot.innerHTML = html + datalistHtml;'),'Datalists and all input groups remain in original root');
assert.ok(html.includes("field.hidden=!show")&&html.includes('section.hidden=!inSection'),'Filters hide only presentation');
assert.ok(html.includes('modalChangedFields()')&&html.includes('changeSet.payload'),'Keep the v2.68 diff-only save logic');
assert.ok(html.includes("if (editorModalSaving || readOnlyTables.has(editorModalTable)) return;"),'No concurrent save and read-only mutation');
assert.ok(html.includes("Hai modifiche non salvate. Vuoi chiudere senza salvarle?"),'Keep unsaved changes warning');
assert.ok(html.includes("modal.setAttribute('aria-hidden','false')")&&html.includes("modal.setAttribute('aria-hidden','true')"),'Dialog aria-hidden state matches visibility');
assert.ok(html.includes("if(focusReturn?.isConnected)focusReturn.focus()"),'Focus returns to opener');
assert.ok(html.includes("document.getElementById('editor-modal-only-changed').disabled=readOnly"),'Read-only archives cannot show changed-only mode');
assert.doesNotMatch(helper,/localStorage|fetch\(|supabase|\.from\(|MutationObserver/,'Presentation helper cannot query DB or observe DOM');
console.log('OK v2.78: grouped modal fields, search filters, safe-save invariants, input retention and focus');