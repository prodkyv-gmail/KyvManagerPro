const assert=require('node:assert/strict');const fs=require('fs');
const economy=fs.readFileSync('kyv-economy-v6.js','utf8');
const html=fs.readFileSync('fatture.html','utf8');
const config=fs.readFileSync('config.js','utf8');
const sw=fs.readFileSync('sw.js','utf8');
for(const label of ['Fatturato','Incassato','Da incassare','Costi registrati','Margine incassato','Previsionale minimo','Fee da fatturare','Controlli di chiusura']) assert.ok(economy.includes(label),label+' missing');
assert.ok(economy.includes("c.from('PROGETTI')"),'PROGETTI source missing');
assert.ok(economy.includes("c.from('FATTURE')"),'FATTURE source missing');
assert.ok(economy.includes("c.from('Spese Extra')"),'cost source missing');
assert.ok(economy.includes('projectInvoices'),'modern/legacy invoice relation logic missing');
assert.ok(economy.includes('IDFT'),'legacy IDFT missing');
assert.doesNotMatch(economy,/\b(?:p\.)?FT\b/,'invoice number FT must not be used for project relations');
assert.ok(economy.includes('daIncassare+feeDaFatturare'),'minimum forecast rule missing');
assert.doesNotMatch(economy,/\.(?:insert|update|upsert|delete)\(/,'economy dashboard must remain read-only');
assert.doesNotMatch(economy,/new MutationObserver/,'economy dashboard must not add MutationObserver');
assert.ok(html.includes('FATTURE DA INCASSARE'),'invoice wording must reflect receivables');
assert.ok(html.includes('ImportoTotaleDocumento, PrezzoUnitario, PrezzoTotale, ImportoPagamento'),'invoice register must use available total amount fields');
assert.ok(config.includes("economy.src='kyv-economy-v6.js'"),'config must load economy v6');
assert.ok(sw.includes("'./kyv-economy-v6.js'"),'PWA must cache economy v6');
console.log('OK: Economy v6 professional dashboard is read-only and relation-safe.');
