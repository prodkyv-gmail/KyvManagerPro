const assert=require('node:assert/strict'),fs=require('node:fs'),vm=require('node:vm');
const read=p=>fs.readFileSync(p,'utf8'),root={},ctx={window:root,Intl,Date,URL,Object,Number,Error,Map,Set};
for(const path of ['kyv-audio-finder-v245.js','kyv-audio-review-v246.js','kyv-audio-groups-v249.js'])vm.runInNewContext(read(path),ctx,{filename:path});
const G=root.KYV_AUDIO_GROUPS_V249,R=root.KYV_AUDIO_REVIEW_V246;
const f=(id,name,provider)=>({id,nome_file:name,provider,account_label:'Studio',external_key:id,mime_type:'audio/wav'});
const files=[f('l','Luce blu demo.wav','local'),f('d','Luce blu mix.wav','drive'),f('p','Luce blu master.wav','dropbox')];
const group=G.groups(files,[]).find(x=>x.files.length===3);
assert.ok(group,'All verified-personal versions must remain one advisory group');
assert.equal(G.scopedToProvider(group,'',[]),group,'All sources remains cross-provider');
const drive=G.scopedToProvider(group,'drive',[]),local=G.scopedToProvider(group,'local',[]);
assert.deepEqual(Array.from(drive.files.map(x=>x.file.id)),['d'],'Drive filter must show only Drive file');
assert.deepEqual(Array.from(drive.providers),['drive']);
assert.deepEqual(Array.from(drive.versionKinds),['Mix']);
assert.equal(drive.unlinkedCount,1);
assert.deepEqual(Array.from(local.files.map(x=>x.file.id)),['l']);
assert.equal(G.scopedToProvider(group,'onedrive',[]),null,'Unavailable source must never leak group files');
assert.equal(group.files.length,3,'Provider filtering must not mutate original advisory group');
assert.equal(G.allowedForLink(drive,[]).length,1);
const projects=[{ID:9,TITOLO:'Luce blu',ARTISTA:'Unknown'}];
const plan=G.planVersionLinks({group:drive,selectedIds:['d'],projectId:9,files,projects,links:[],owner:'user',review:R});
assert.equal(plan.length,1);
assert.throws(()=>G.planVersionLinks({group:drive,selectedIds:['l'],projectId:9,files,projects,links:[],owner:'user',review:R}),/non autorizzate/,'Cannot link hidden Local file when Drive is selected');
assert.throws(()=>G.planVersionLinks({group:drive,selectedIds:['p'],projectId:9,files,projects,links:[],owner:'user',review:R}),/non autorizzate/,'Cannot link hidden Dropbox file');
const linked=[{id_audio:'d',id_progetto:9,confermata:true,annullata:false}];
const scopedLinked=G.scopedToProvider(group,'drive',linked);
assert.equal(scopedLinked.unlinkedCount,0,'Active links must be reflected in scope');
assert.equal(scopedLinked.linkedProjectIds.length,1);
assert.equal(G.allowedForLink(scopedLinked,linked).length,0);
assert.equal(G.scopedToProvider(null,'local',[]),null);
const ui=read('kyv-audio-finder-ui-v245.js'),page=read('kyv_audio_finder.html'),sw=read('sw.js');
assert.ok(ui.includes('function selectedGroupView()'),'One selected-group source scope function');
assert.ok(ui.includes('const g=selectedGroupView();if(!g)return;'),'Bulk group selection limited by source');
assert.ok(ui.includes("G.scopedToProvider(all.find(x=>x.key===groupKey),$('finder-group-source').value,links)"),'Detail hides out-of-source files');
assert.ok(ui.includes('const g=selectedGroupView();if(!g)throw Error'),'Save must use same scope as detail');
