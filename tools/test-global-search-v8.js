const assert=require('node:assert/strict');const fs=require('fs');
const search=fs.readFileSync('kyv-global-search-v8.js','utf8');
const config=fs.readFileSync('config.js','utf8');
const sw=fs.readFileSync('sw.js','utf8');
for(const source of ["c.from('PROGETTI')","c.from('FATTURE')","c.from('INVII_AUDIO')","c.from('DOCUMENTI_PROGETTO')","c.from('AUDIO_VERSIONI')","c.from('EXPORT SIAE')","c.from('ESTRATTO_IMAIE')"]) assert.ok(search.includes(source),source+' missing');
for(const type of ['Progetto','Fattura','Invio','Documento','Versione','SIAE','IMAIE']) assert.ok(search.includes("'"+type+"'"),type+' entity missing');
assert.ok(search.includes("(e.metaKey||e.ctrlKey)&&e.key.toLowerCase()==='k'"),'Cmd/Ctrl+K shortcut missing');
assert.ok(search.includes("e.key==='ArrowDown'"),'keyboard down navigation missing');
assert.ok(search.includes("e.key==='ArrowUp'"),'keyboard up navigation missing');
assert.ok(search.includes("e.key==='Enter'"),'keyboard open missing');
assert.ok(search.includes("e.key==='Escape'"),'Escape close missing');
assert.ok(search.includes('kyv-global-search-button'),'sidebar search trigger missing');
assert.ok(search.includes('recentItems'),'in-page recent results missing');
assert.ok(!search.includes('localStorage'),'Search must not persist private record names across users');
assert.ok(search.includes('if(index)return index;if(loading)return loading'),'search index must be cached in memory');
assert.ok(search.includes("if(!q){"),'empty-query recent state missing');
assert.ok(search.includes("if(q.length<2)"),'minimum search length missing');
assert.ok(search.includes("r.type!==previousType"),'results must be grouped by entity');
assert.doesNotMatch(search,/\.(?:insert|update|upsert|delete)\(/,'global search must remain read-only');
assert.doesNotMatch(search,/new MutationObserver/,'global search must not add observer');
assert.ok(config.includes("globalSearch.src='kyv-global-search-v8.js'"),'config must load global search');
assert.ok(sw.includes("'./kyv-global-search-v8.js'"),'PWA must cache global search');
console.log('OK: Global Search v8 is on-demand, grouped, keyboard-first and read-only.');
