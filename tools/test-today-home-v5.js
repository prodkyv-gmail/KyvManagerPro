const assert=require('node:assert/strict');const fs=require('fs');
const home=fs.readFileSync('kyv-today-home-v5.js','utf8');
const config=fs.readFileSync('config.js','utf8');
const producer=fs.readFileSync('kyv-producer-mode.js','utf8');
const sw=fs.readFileSync('sw.js','utf8');
for(const label of ['Oggi','Questa settimana','Da controllare','Da incassare']) assert.ok(home.includes(label),label+' summary missing');
assert.ok(home.includes('.slice(0,5)'),'home must cap priorities at five');
assert.ok(home.includes("rows('PROGETTI'"),'PROGETTI source missing');
assert.ok(home.includes("rows('FATTURE'"),'FATTURE source missing');
assert.ok(home.includes("rows('INVII_AUDIO'"),'INVII_AUDIO source missing');
assert.ok(home.includes('FOLLOWUP_DAYS=5'),'follow-up rule missing');
assert.ok(home.includes('Data_Pubblicazione'),'release priority missing');
assert.ok(home.includes('Data_Sessione'),'session priority missing');
assert.ok(home.includes('Incasso da verificare'),'money priority missing');
assert.doesNotMatch(home,/\.(?:insert|update|upsert|delete)\(/,'Today Home must remain read-only');
