// v2.37: immutable reversals, audits, and full payment-accounting regressions
const fs=require('node:fs'),vm=require('node:vm'),assert=require('node:assert/strict');
const source=fs.readFileSync('kyv-invoice-reconciliation-v236.js','utf8');
const html=fs.readFileSync('fatture.html','utf8');
const sql=fs.readFileSync('docs/v237-payment-reversals.sql','utf8');
const sw=fs.readFileSync('sw.js','utf8');
const window={KYV:{parseNumber(v){const t=String(v??'');return Number(t.includes(',')?t.replace(/\./g,'').replace(',','.'):t)||0;},formatEuro:n=>String(n),isPaid:v=>/^si$/i.test(v)}};
vm.runInNewContext(source,{window,Intl,Date,Number,console});
const a=window.KYV_COLLECTIONS_V236;
const invoice=(paid='NO')=>({ID_FT:1,ImportoTotaleDocumento:'1000.00',PAGATA:paid});
const pay=[{ID_INCASSO:5,ID_FT:1,Importo:400},{ID_INCASSO:6,ID_FT:1,Importo:600}];
const reversal=[{ID_STORNO:8,ID_INCASSO:5,Data:'2026-10-29',Motivo:'Movimento registrato sul cliente errato'}];
let s=a.summarize(invoice(),pay,reversal);
assert.equal(s.received,600);assert.equal(s.remaining,400);assert.equal(s.kind,'partial');assert.equal(s.reversedMovementCount,1);
assert.equal(a.summarize(invoice(),pay,[]).remaining,0);
s=a.summarize(invoice('SI'),pay,[...reversal,{ID_STORNO:9,ID_INCASSO:6}]);
assert.equal(s.received,0,'All reversed payments yield zero, even if old PAGATA=SI');
assert.equal(s.remaining,1000);assert.equal(s.legacyPaid,false);
assert.equal(a.summarize(invoice('SI'),[],[]).received,1000,'Historic invoices retain old paid behavior');
assert.equal(a.summarize(invoice(),pay,[{ID_INCASSO:6}]).received,400);
assert.ok(source.includes('FATTURE_INCASSI_STORNI'));
assert.ok(source.includes("data-recon-reverse"));
assert.ok(source.includes('Storna incasso'));
assert.ok(source.includes('Motivo dello storno'));
assert.ok(source.includes('existing.data?.length'));
assert.ok(source.includes('window.confirm('));
assert.ok(source.includes('state.reversals'));
assert.ok(html.includes('kyv-invoice-reconciliation-v236.js'),'Existing invoice page must include module');
assert.ok(sw.includes('kyv-studio-v2-38-intelligence-20261029'));
assert.match(sql,/unique references public\."FATTURE_INCASSI"/i,'Only one reversal per payment');
assert.match(sql,/char_length\(btrim\("Motivo"\)\) between 10 and 500/);
assert.match(sql,/enable row level security/i);
assert.doesNotMatch(sql,/delete from public|update public\."FATTURE_INCASSI"/i);
console.log('OK: immutable v2.37 payment reversals, audit and historic balances');
