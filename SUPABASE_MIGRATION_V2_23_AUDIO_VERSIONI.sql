-- KYV Studio Manager Pro v2.23
-- Archivio audio unificato e salvataggio atomico progetto + versione.
--
-- Eseguire una sola volta nel SQL Editor di Supabase e verificare l'esito prima
-- di usare il nuovo flusso. Lo script e' ripetibile e non elimina dati.
--
-- NOTA ACCESSI
-- La v2.22 (autenticazione e isolamento per utente) e' stata sospesa. Le policy
-- contrassegnate "compatibilita v2.23" mantengono quindi l'accesso anonimo gia'
-- usato dall'app corrente. Dovranno essere sostituite dalle policy per utente
-- quando verra' ripresa la v2.22.

begin;

create table if not exists public."AUDIO_VERSIONI" (
  "ID_VERSIONE" bigint generated by default as identity primary key,
  "ID_PROGETTO" bigint not null references public."PROGETTI"("ID") on delete restrict,
  "PROVIDER" text not null,
  "PROVIDER_ID" text null,
  "REVISIONE_PROVIDER" text null,
  "NOME_FILE" text not null,
  "TITOLO" text null,
  "ARTISTA" text null,
  "TIPO_VERSIONE" text null,
  "ETICHETTA_VERSIONE" text null,
  "STATO_VERSIONE" text not null default 'Archiviata',
  "LINK_FILE" text null,
  "CONTENT_HASH" text null,
  "FONTE_LABEL" text null,
  "DATA_FILE" timestamptz null,
  "METADATI" jsonb not null default '{}'::jsonb,
  "NOTE" text null,
  "DEDUPE_KEY" text not null,
  "created_at" timestamptz not null default now(),
  "updated_at" timestamptz not null default now(),
  constraint "audio_versioni_provider_chk"
    check ("PROVIDER" in ('drive', 'dropbox', 'local', 'altro')),
  constraint "audio_versioni_identita_chk"
    check (
      nullif(btrim(coalesce("PROVIDER_ID", '')), '') is not null
      or nullif(btrim(coalesce("CONTENT_HASH", '')), '') is not null
      or nullif(btrim(coalesce("LINK_FILE", '')), '') is not null
      or nullif(btrim(coalesce("NOME_FILE", '')), '') is not null
    )
);

create unique index if not exists "uq_audio_versioni_dedupe_key"
  on public."AUDIO_VERSIONI" ("DEDUPE_KEY");

create index if not exists "idx_audio_versioni_progetto_data"
  on public."AUDIO_VERSIONI" ("ID_PROGETTO", "DATA_FILE" desc, "ID_VERSIONE" desc);

create index if not exists "idx_audio_versioni_progetto_fk"
  on public."AUDIO_VERSIONI" ("ID_PROGETTO");

create index if not exists "idx_audio_versioni_provider_id"
  on public."AUDIO_VERSIONI" ("PROVIDER", "PROVIDER_ID", "REVISIONE_PROVIDER")
  where "PROVIDER_ID" is not null;

create index if not exists "idx_audio_versioni_content_hash"
  on public."AUDIO_VERSIONI" ("CONTENT_HASH")
  where "CONTENT_HASH" is not null;

create or replace function public.kyv_audio_dedupe_key(
  p_provider text,
  p_provider_id text,
  p_provider_revision text,
  p_content_hash text,
  p_link text,
  p_file_name text
)
returns text
language sql
immutable
security invoker
set search_path = ''
as $function$
  select md5(
    case
      when nullif(btrim(coalesce(p_provider_id, '')), '') is not null then
        lower(btrim(coalesce(p_provider, 'altro'))) || '|id|' ||
        lower(btrim(p_provider_id)) || '|rev|' ||
        lower(btrim(coalesce(nullif(p_provider_revision, ''), nullif(p_content_hash, ''), 'corrente')))
      when nullif(btrim(coalesce(p_content_hash, '')), '') is not null then
        'hash|' || lower(btrim(p_content_hash))
      when nullif(btrim(coalesce(p_link, '')), '') is not null then
        lower(btrim(coalesce(p_provider, 'altro'))) || '|link|' || lower(btrim(p_link))
      else
        lower(btrim(coalesce(p_provider, 'altro'))) || '|file|' ||
        lower(btrim(coalesce(p_file_name, 'senza-nome'))) || '|rev|' ||
        lower(btrim(coalesce(nullif(p_provider_revision, ''), 'corrente')))
    end
  );
$function$;

create or replace function public.kyv_set_audio_updated_at_v23()
returns trigger
language plpgsql
security invoker
set search_path = ''
as $function$
begin
  new."updated_at" := pg_catalog.now();
  return new;
end;
$function$;

drop trigger if exists "trg_audio_versioni_updated_at" on public."AUDIO_VERSIONI";
create trigger "trg_audio_versioni_updated_at"
before update on public."AUDIO_VERSIONI"
for each row execute function public.kyv_set_audio_updated_at_v23();

-- Recupera le versioni Dropbox gia' presenti. I record orfani vengono ignorati
-- per non inventare collegamenti a progetti inesistenti.
insert into public."AUDIO_VERSIONI" (
  "ID_PROGETTO", "PROVIDER", "PROVIDER_ID", "REVISIONE_PROVIDER",
  "NOME_FILE", "TITOLO", "ARTISTA", "TIPO_VERSIONE", "ETICHETTA_VERSIONE",
  "LINK_FILE", "CONTENT_HASH", "FONTE_LABEL", "DATA_FILE", "METADATI", "NOTE", "DEDUPE_KEY"
)
select
  d."ID_PROGETTO",
  'dropbox',
  substring(coalesce(d."Note", '') from 'Origine ID:[[:space:]]*Dropbox:([^[:space:]]+)'),
  substring(coalesce(d."Note", '') from 'Revisione Dropbox:[[:space:]]*([^[:space:]]+)'),
  coalesce(nullif(d."Nome_File", ''), nullif(d."Titolo", ''), 'File Dropbox #' || d."ID_FILE"::text),
  d."Titolo",
  d."Artista",
  d."Tipo_File",
  d."Versione",
  d."Link_Dropbox",
  d."Hash_SHA256",
  'Dropbox',
  d."Data_Caricamento"::timestamptz,
  jsonb_build_object('origine_legacy', 'DROPBOX_AUDIO_FILES', 'id_legacy', d."ID_FILE"),
  d."Note",
  public.kyv_audio_dedupe_key(
    'dropbox',
    substring(coalesce(d."Note", '') from 'Origine ID:[[:space:]]*Dropbox:([^[:space:]]+)'),
    substring(coalesce(d."Note", '') from 'Revisione Dropbox:[[:space:]]*([^[:space:]]+)'),
    d."Hash_SHA256",
    d."Link_Dropbox",
    coalesce(nullif(d."Nome_File", ''), nullif(d."Titolo", ''), 'File Dropbox #' || d."ID_FILE"::text)
  )
from public."DROPBOX_AUDIO_FILES" d
join public."PROGETTI" p on p."ID" = d."ID_PROGETTO"
where nullif(btrim(coalesce(d."Link_Dropbox", '')), '') is not null
on conflict ("DEDUPE_KEY") do nothing;

-- Recupera i documenti Drive che rappresentano versioni audio.
insert into public."AUDIO_VERSIONI" (
  "ID_PROGETTO", "PROVIDER", "PROVIDER_ID", "REVISIONE_PROVIDER",
  "NOME_FILE", "TITOLO", "TIPO_VERSIONE", "LINK_FILE", "FONTE_LABEL",
  "DATA_FILE", "METADATI", "NOTE", "DEDUPE_KEY"
)
select
  d."ID_PROGETTO",
  'drive',
  substring(coalesce(d."Note", '') from 'Origine ID:[[:space:]]*Drive:([^[:space:]]+)'),
  d."Data_Documento"::text,
  coalesce(nullif(d."Titolo_Documento", ''), 'File Drive #' || d."ID_DOCUMENTO"::text),
  d."Titolo_Documento",
  coalesce(substring(coalesce(d."Note", '') from 'Tipo:[[:space:]]*([^\n\r]+)'), 'Versione audio'),
  d."Link_Drive",
  coalesce(nullif(d."Fonte", ''), 'Google Drive'),
  d."Data_Documento"::timestamptz,
  jsonb_build_object('origine_legacy', 'DOCUMENTI_PROGETTO', 'id_legacy', d."ID_DOCUMENTO"),
  d."Note",
  public.kyv_audio_dedupe_key(
    'drive',
    substring(coalesce(d."Note", '') from 'Origine ID:[[:space:]]*Drive:([^[:space:]]+)'),
    d."Data_Documento"::text,
    null,
    d."Link_Drive",
    coalesce(nullif(d."Titolo_Documento", ''), 'File Drive #' || d."ID_DOCUMENTO"::text)
  )
from public."DOCUMENTI_PROGETTO" d
join public."PROGETTI" p on p."ID" = d."ID_PROGETTO"
where coalesce(d."Tipo_Documento", '') ~* 'audio[_ -]?drive|versione audio'
  and nullif(btrim(coalesce(d."Link_Drive", '')), '') is not null
on conflict ("DEDUPE_KEY") do nothing;

create or replace function public.kyv_salva_audio_v23(
  p_project_id bigint,
  p_project_data jsonb,
  p_audio_data jsonb
)
returns jsonb
language plpgsql
security invoker
set search_path = ''
as $function$
declare
  v_project public."PROGETTI"%rowtype;
  v_version public."AUDIO_VERSIONI"%rowtype;
  v_existing public."AUDIO_VERSIONI"%rowtype;
  v_project_created boolean := false;
  v_duplicate boolean := false;
  v_provider text;
  v_provider_id text;
  v_provider_revision text;
  v_file_name text;
  v_link text;
  v_hash text;
  v_dedupe_key text;
  v_file_date timestamptz;
  v_identity_note text;
  v_note text;
  v_seq_name text;
  v_next_id bigint;
begin
  if p_audio_data is null then
    raise exception using message = 'Dati della versione audio mancanti.', errcode = '22023';
  end if;

  v_provider := lower(btrim(coalesce(p_audio_data->>'provider', 'altro')));
  if v_provider not in ('drive', 'dropbox', 'local', 'altro') then
    v_provider := 'altro';
  end if;
  v_provider_id := nullif(btrim(coalesce(p_audio_data->>'provider_id', '')), '');
  v_provider_revision := nullif(btrim(coalesce(p_audio_data->>'provider_revision', '')), '');
  v_file_name := coalesce(nullif(btrim(coalesce(p_audio_data->>'file_name', '')), ''), 'File audio');
  v_link := nullif(btrim(coalesce(p_audio_data->>'link', '')), '');
  v_hash := nullif(btrim(coalesce(p_audio_data->>'content_hash', '')), '');
  v_file_date := nullif(btrim(coalesce(p_audio_data->>'file_date', '')), '')::timestamptz;
  v_dedupe_key := public.kyv_audio_dedupe_key(
    v_provider, v_provider_id, v_provider_revision, v_hash, v_link, v_file_name
  );
  -- Due richieste concorrenti per la stessa revisione vengono serializzate.
  -- L'indice unico resta il vincolo finale; questo lock evita che due progetti
  -- diversi arrivino contemporaneamente allo stesso ON CONFLICT.
  perform pg_catalog.pg_advisory_xact_lock(
    pg_catalog.hashtext('kyv.audio.dedupe.' || v_dedupe_key)
  );

  if p_project_id is null then
    if nullif(btrim(coalesce(p_project_data->>'title', '')), '') is null then
      raise exception using message = 'Titolo del progetto mancante.', errcode = '22023';
    end if;

    -- Serializza soltanto la scelta del prossimo ID e riallinea la sequenza,
    -- evitando collisioni senza tenere lock durante chiamate esterne.
    perform pg_catalog.pg_advisory_xact_lock(pg_catalog.hashtext('kyv.progetti.nuovo_id'));
    select pg_catalog.pg_get_serial_sequence('public."PROGETTI"', 'ID') into v_seq_name;
    select coalesce(max(p."ID"), 0) + 1 into v_next_id from public."PROGETTI" p;

    if v_seq_name is not null then
      perform pg_catalog.setval(v_seq_name::regclass, v_next_id, false);
      insert into public."PROGETTI" (
        "TITOLO", "ARTISTA", "STATO", "SVILUPPO", "NOTE", "MANAGEMENT", "Label", "Data_Sessione"
      ) values (
        btrim(p_project_data->>'title'),
        nullif(btrim(coalesce(p_project_data->>'artist', '')), ''),
        'In produzione',
        'WIP',
        nullif(btrim(coalesce(p_project_data->>'note', '')), ''),
        nullif(btrim(coalesce(p_project_data->>'management', '')), ''),
        nullif(btrim(coalesce(p_project_data->>'label', '')), ''),
        nullif(btrim(coalesce(p_project_data->>'session_date', '')), '')::date
      ) returning * into v_project;
    else
      insert into public."PROGETTI" (
        "ID", "TITOLO", "ARTISTA", "STATO", "SVILUPPO", "NOTE", "MANAGEMENT", "Label", "Data_Sessione"
      ) values (
        v_next_id,
        btrim(p_project_data->>'title'),
        nullif(btrim(coalesce(p_project_data->>'artist', '')), ''),
        'In produzione',
        'WIP',
        nullif(btrim(coalesce(p_project_data->>'note', '')), ''),
        nullif(btrim(coalesce(p_project_data->>'management', '')), ''),
        nullif(btrim(coalesce(p_project_data->>'label', '')), ''),
        nullif(btrim(coalesce(p_project_data->>'session_date', '')), '')::date
      ) returning * into v_project;
    end if;
    v_project_created := true;
  else
    select p.* into v_project
    from public."PROGETTI" p
    where p."ID" = p_project_id
    for update;

    if not found then
      raise exception using message = 'Progetto non trovato.', errcode = 'P0002';
    end if;
  end if;

  select a.* into v_existing
  from public."AUDIO_VERSIONI" a
  where a."DEDUPE_KEY" = v_dedupe_key
  for update;

  if found then
    v_duplicate := true;
    if v_existing."ID_PROGETTO" <> v_project."ID" then
      raise exception using
        message = format('Questa versione audio e'' gia'' collegata al progetto #%s.', v_existing."ID_PROGETTO"),
        errcode = '23505';
    end if;
  end if;

  v_identity_note := case
    when v_provider_id is not null then
      'Origine ID: ' || initcap(v_provider) || ':' || v_provider_id
    else null
  end;
  v_note := concat_ws(E'\n', v_identity_note, nullif(btrim(coalesce(p_audio_data->>'note', '')), ''));

  insert into public."AUDIO_VERSIONI" as current_audio (
    "ID_PROGETTO", "PROVIDER", "PROVIDER_ID", "REVISIONE_PROVIDER", "NOME_FILE",
    "TITOLO", "ARTISTA", "TIPO_VERSIONE", "ETICHETTA_VERSIONE", "STATO_VERSIONE",
    "LINK_FILE", "CONTENT_HASH", "FONTE_LABEL", "DATA_FILE", "METADATI", "NOTE", "DEDUPE_KEY"
  ) values (
    v_project."ID", v_provider, v_provider_id, v_provider_revision, v_file_name,
    nullif(btrim(coalesce(p_audio_data->>'title', '')), ''),
    nullif(btrim(coalesce(p_audio_data->>'artist', '')), ''),
    nullif(btrim(coalesce(p_audio_data->>'file_type', '')), ''),
    nullif(btrim(coalesce(p_audio_data->>'version', '')), ''),
    coalesce(nullif(btrim(coalesce(p_audio_data->>'status', '')), ''), 'Archiviata'),
    v_link, v_hash,
    nullif(btrim(coalesce(p_audio_data->>'source_label', '')), ''),
    v_file_date,
    coalesce(p_audio_data->'metadata', '{}'::jsonb),
    nullif(v_note, ''),
    v_dedupe_key
  )
  on conflict ("DEDUPE_KEY") do update set
    "NOME_FILE" = excluded."NOME_FILE",
    "TITOLO" = coalesce(excluded."TITOLO", current_audio."TITOLO"),
    "ARTISTA" = coalesce(excluded."ARTISTA", current_audio."ARTISTA"),
    "TIPO_VERSIONE" = coalesce(excluded."TIPO_VERSIONE", current_audio."TIPO_VERSIONE"),
    "ETICHETTA_VERSIONE" = coalesce(excluded."ETICHETTA_VERSIONE", current_audio."ETICHETTA_VERSIONE"),
    "STATO_VERSIONE" = excluded."STATO_VERSIONE",
    "LINK_FILE" = coalesce(excluded."LINK_FILE", current_audio."LINK_FILE"),
    "CONTENT_HASH" = coalesce(excluded."CONTENT_HASH", current_audio."CONTENT_HASH"),
    "FONTE_LABEL" = coalesce(excluded."FONTE_LABEL", current_audio."FONTE_LABEL"),
    "DATA_FILE" = coalesce(excluded."DATA_FILE", current_audio."DATA_FILE"),
    "METADATI" = current_audio."METADATI" || excluded."METADATI",
    "NOTE" = coalesce(excluded."NOTE", current_audio."NOTE")
  returning * into v_version;

  -- Specchio di compatibilita': le pagine precedenti continuano a vedere gli
  -- stessi dati, ma vengono aggiornate nella medesima transazione.
  if v_provider = 'dropbox' then
    if v_link is null then
      raise exception using message = 'Link Dropbox mancante.', errcode = '22023';
    end if;

    update public."DROPBOX_AUDIO_FILES"
    set
      "ID_PROGETTO" = v_project."ID",
      "Progetto" = concat_ws(' - ', nullif(v_project."ARTISTA", ''), v_project."TITOLO"),
      "Artista" = coalesce(v_project."ARTISTA", nullif(p_audio_data->>'artist', '')),
      "Titolo" = coalesce(v_project."TITOLO", nullif(p_audio_data->>'title', '')),
      "Tipo_File" = nullif(p_audio_data->>'file_type', ''),
      "Versione" = nullif(p_audio_data->>'version', ''),
      "Nome_File" = v_file_name,
      "Hash_SHA256" = v_hash,
      "Data_Caricamento" = coalesce(v_file_date::date, current_date),
      "Note" = nullif(concat_ws(E'\n', v_identity_note,
        case when v_provider_revision is not null then 'Revisione Dropbox: ' || v_provider_revision end,
        nullif(p_audio_data->>'note', '')), '')
    where "ID_FILE" = (
      select d."ID_FILE" from public."DROPBOX_AUDIO_FILES" d
      where d."Link_Dropbox" = v_link
      order by d."ID_FILE" limit 1
    );

    if not found then
      insert into public."DROPBOX_AUDIO_FILES" (
        "ID_PROGETTO", "Progetto", "Artista", "Titolo", "Tipo_File", "Versione",
        "Nome_File", "Link_Dropbox", "Hash_SHA256", "Data_Caricamento", "Note"
      ) values (
        v_project."ID", concat_ws(' - ', nullif(v_project."ARTISTA", ''), v_project."TITOLO"),
        coalesce(v_project."ARTISTA", nullif(p_audio_data->>'artist', '')),
        coalesce(v_project."TITOLO", nullif(p_audio_data->>'title', '')),
        nullif(p_audio_data->>'file_type', ''), nullif(p_audio_data->>'version', ''),
        v_file_name, v_link, v_hash, coalesce(v_file_date::date, current_date),
        nullif(concat_ws(E'\n', v_identity_note,
          case when v_provider_revision is not null then 'Revisione Dropbox: ' || v_provider_revision end,
          nullif(p_audio_data->>'note', '')), '')
      );
    end if;
  elsif v_provider = 'drive' then
    if v_link is null then
      raise exception using message = 'Link Google Drive mancante.', errcode = '22023';
    end if;

    update public."DOCUMENTI_PROGETTO"
    set
      "Tipo_Documento" = 'AUDIO_DRIVE',
      "Titolo_Documento" = v_file_name,
      "Fonte" = coalesce(nullif(p_audio_data->>'source_label', ''), 'Google Drive'),
      "Data_Documento" = coalesce(v_file_date::date, current_date),
      "Note" = nullif(concat_ws(E'\n', v_identity_note,
        'Tipo: ' || coalesce(nullif(p_audio_data->>'file_type', ''), 'Versione audio'),
        case when nullif(p_audio_data->>'version', '') is not null then 'Versione: ' || (p_audio_data->>'version') end,
        nullif(p_audio_data->>'note', '')), '')
    where "ID_DOCUMENTO" = (
      select d."ID_DOCUMENTO" from public."DOCUMENTI_PROGETTO" d
      where d."ID_PROGETTO" = v_project."ID" and d."Link_Drive" = v_link
      order by d."ID_DOCUMENTO" limit 1
    );

    if not found then
      insert into public."DOCUMENTI_PROGETTO" (
        "ID_PROGETTO", "Tipo_Documento", "Titolo_Documento", "Fonte", "Link_Drive", "Data_Documento", "Note"
      ) values (
        v_project."ID", 'AUDIO_DRIVE', v_file_name,
        coalesce(nullif(p_audio_data->>'source_label', ''), 'Google Drive'),
        v_link, coalesce(v_file_date::date, current_date),
        nullif(concat_ws(E'\n', v_identity_note,
          'Tipo: ' || coalesce(nullif(p_audio_data->>'file_type', ''), 'Versione audio'),
          case when nullif(p_audio_data->>'version', '') is not null then 'Versione: ' || (p_audio_data->>'version') end,
          nullif(p_audio_data->>'note', '')), '')
      );
    end if;
  end if;

  return jsonb_build_object(
    'project', to_jsonb(v_project),
    'version', to_jsonb(v_version),
    'createdProject', v_project_created,
    'duplicate', v_duplicate
  );
end;
$function$;

