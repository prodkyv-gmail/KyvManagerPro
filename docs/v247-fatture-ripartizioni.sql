-- v2.47 - one fiscal invoice, many project-level unit-fee allocations.
-- Additive: no changes to historical FATTURE, PROGETTI or payment records.
create table if not exists public."FATTURE_RIPARTIZIONI"(
 id bigint generated by default as identity primary key,
 owner_id uuid not null default auth.uid() references auth.users(id),
 id_ft bigint not null references public."FATTURE"("ID_FT") on delete restrict,
 id_progetto bigint not null references public."PROGETTI"("ID") on delete restrict,
 prezzo_unitario numeric(14,2) not null check(prezzo_unitario>=0),
 descrizione text not null default '' check(length(descrizione)<=500),
 fee_riferimento numeric(14,2) check(fee_riferimento is null or fee_riferimento>=0),
 created_at timestamptz not null default now()
);
create index if not exists fatture_rip_owner_invoice on public."FATTURE_RIPARTIZIONI"(owner_id,id_ft);
create index if not exists fatture_rip_owner_project on public."FATTURE_RIPARTIZIONI"(owner_id,id_progetto);
alter table public."FATTURE_RIPARTIZIONI" enable row level security;
create policy rip_own_read on public."FATTURE_RIPARTIZIONI" for select to authenticated
 using(owner_id=(select auth.uid()));
create policy rip_own_insert on public."FATTURE_RIPARTIZIONI" for insert to authenticated
 with check(owner_id=(select auth.uid()) and
  exists(select 1 from public."FATTURE" f where f."ID_FT"=id_ft and f.owner_id=owner_id) and
  exists(select 1 from public."PROGETTI" p where p."ID"=id_progetto and p.owner_id=owner_id));
create policy rip_own_delete on public."FATTURE_RIPARTIZIONI" for delete to authenticated
 using(owner_id=(select auth.uid()));
revoke all on public."FATTURE_RIPARTIZIONI" from public, anon, authenticated;
grant select,insert,delete on public."FATTURE_RIPARTIZIONI" to authenticated;

-- Only values from PrezzoUnitario fund managerial allocations; never ImportoTotaleDocumento.
create or replace function public.kyv_v247_number(v text) returns numeric
language plpgsql immutable set search_path=public,pg_temp as $$
declare t text;
begin
 t:=regexp_replace(coalesce(v,''),'[^0-9,.-]','','g');
 if t='' then return null; end if;
 if position(',' in t)>0 then
  t:=replace(replace(t,'.',''),',','.');
 end if;
 return t::numeric;
exception when invalid_text_representation or numeric_value_out_of_range then return null;
end $$;
revoke all on function public.kyv_v247_number(text) from public;
grant execute on function public.kyv_v247_number(text) to authenticated;

-- One database transaction for initial manual invoice + allocations, or for
-- replacing allocations of an existing invoice. Existing invoice fields stay intact.
create or replace function public.kyv_v247_save_invoice(
 p_invoice_id bigint,p_invoice jsonb,p_rows jsonb
) returns bigint
language plpgsql security invoker set search_path=public,pg_temp as $$
declare uid uuid:=auth.uid(); inv_id bigint; inv_total numeric;
 n integer; elem jsonb; pid bigint; part numeric; fee numeric;
 assigned numeric:=0; number_orig text; invoice_day date; client_name text;
begin
 if uid is null then raise exception 'Sessione non autenticata'; end if;
 if p_rows is null or jsonb_typeof(p_rows)<>'array' then raise exception 'Righe mancanti';end if;
 n:=jsonb_array_length(p_rows);
 if n<1 or n>100 then raise exception 'Sono necessarie da 1 a 100 righe';end if;
 if p_invoice_id is null then
  if p_invoice is null or jsonb_typeof(p_invoice)<>'object' then raise exception 'Dati fattura mancanti';end if;
  number_orig:=btrim(coalesce(p_invoice->>'numero',''));
  client_name:=btrim(coalesce(p_invoice->>'cliente',''));
  if length(number_orig)<1 or length(number_orig)>150 or
   length(client_name)<1 or length(client_name)>300 then raise exception 'Numero o cliente non valido';end if;
  invoice_day:=(p_invoice->>'data')::date;
  if invoice_day is null then raise exception 'Data fattura obbligatoria'; end if;
  inv_total:=(p_invoice->>'prezzo_unitario')::numeric;
  if inv_total is null or inv_total<0 or inv_total>999999999999 then raise exception 'Prezzo unitario gestionale non valido';end if;
  -- Serialise competing requests for the same owner + year + original invoice number.
  perform pg_advisory_xact_lock(hashtextextended(uid::text||extract(year from invoice_day)||lower(number_orig),0));
  if exists(select 1 from public."FATTURE" f where f.owner_id=uid and
   extract(year from f."Data")=extract(year from invoice_day) and
   lower(btrim(coalesce(f."Numero_Originale",f."Numero"::text,'')))=lower(number_orig))
  then raise exception 'Fattura già presente: aprila e aggiungi righe alla fattura esistente';end if;
  insert into public."FATTURE"(
   owner_id,"Numero_Originale","Data","Denominazione","Descrizione",
   "PrezzoUnitario","ImportoTotaleDocumento","PAGATA","ID_PROGETTO")
  values(uid,number_orig,invoice_day,client_name,left(coalesce(p_invoice->>'descrizione',''),1200),
   to_char(inv_total,'FM999999999990.00'),
   nullif(p_invoice->>'totale_fiscale',''),
   'NO',null)
  returning "ID_FT" into inv_id;
 else
  select f."ID_FT",public.kyv_v247_number(f."PrezzoUnitario")
   into inv_id,inv_total from public."FATTURE" f
   where f."ID_FT"=p_invoice_id and f.owner_id=uid for update;
  if inv_id is null then raise exception 'Fattura non trovata o senza autorizzazione';end if;
  if inv_total is null or inv_total<0 then raise exception 'Completa PrezzoUnitario nella fattura prima di ripartirla';end if;
 end if;
 for elem in select value from jsonb_array_elements(p_rows) loop
  if jsonb_typeof(elem)<>'object' then raise exception 'Riga non valida';end if;
  pid:=(elem->>'id_progetto')::bigint;
  part:=(elem->>'prezzo_unitario')::numeric;
  fee:=nullif(elem->>'fee_riferimento','')::numeric;
  if pid is null or part is null or part<0 or part>999999999999 or
    (fee is not null and (fee<0 or fee>999999999999)) then
    raise exception 'Progetto, importo o fee non valido';end if;
  if not exists(select 1 from public."PROGETTI" p where p."ID"=pid and p.owner_id=uid)
   then raise exception 'Progetto non autorizzato: %',pid;end if;
  assigned:=assigned+part;
 end loop;
 if round(assigned,2)>round(inv_total,2) then
  raise exception 'Quote superiori al PrezzoUnitario della fattura: assegnate %; disponibile %',round(assigned,2),round(inv_total,2);
 end if;
 -- Replacing allocations is atomic: the old rows survive if any insert fails.
 delete from public."FATTURE_RIPARTIZIONI" where owner_id=uid and id_ft=inv_id;
 for elem in select value from jsonb_array_elements(p_rows) loop
  insert into public."FATTURE_RIPARTIZIONI"(
    owner_id,id_ft,id_progetto,prezzo_unitario,descrizione,fee_riferimento)
  values(uid,inv_id,(elem->>'id_progetto')::bigint,
   round((elem->>'prezzo_unitario')::numeric,2),left(coalesce(elem->>'descrizione',''),500),
   nullif(elem->>'fee_riferimento','')::numeric);
 end loop;
 return inv_id;
end $$;
revoke all on function public.kyv_v247_save_invoice(bigint,jsonb,jsonb) from public;
grant execute on function public.kyv_v247_save_invoice(bigint,jsonb,jsonb) to authenticated;

comment on table public."FATTURE_RIPARTIZIONI" is
 'Righe gestionali di fee/progetti sotto un solo ID_FT fiscale; PrezzoUnitario, mai ImportoTotaleDocumento.';
